const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  pickFiles: () => ipcRenderer.invoke('pick-files'),
  pickDir: () => ipcRenderer.invoke('pick-dir'),
  expand: (paths) => ipcRenderer.invoke('expand', paths),
  pathForFile: (file) => webUtils.getPathForFile(file),
  inspect: (file) => ipcRenderer.invoke('inspect', file),
  convert: (files, opts) => ipcRenderer.invoke('convert', files, opts),
  reveal: (p) => ipcRenderer.invoke('reveal', p),
  pickPdf: () => ipcRenderer.invoke('pick-pdf'),
  expandPdf: (paths) => ipcRenderer.invoke('expand-pdf', paths),
  readFile: (file) => ipcRenderer.invoke('read-file', file),
  pdfInfo: (file) => ipcRenderer.invoke('pdf-info', file),
  pdfUnlock: (file, password) => ipcRenderer.invoke('pdf-unlock', file, password),
  pdfFields: (file) => ipcRenderer.invoke('pdf-fields', file),
  pdfSaveEdited: (file, opts) => ipcRenderer.invoke('pdf-save-edited', file, opts),
  appVersion: () => ipcRenderer.invoke('app-version'),
  pickVideo: () => ipcRenderer.invoke('pick-video'),
  pickSubs: () => ipcRenderer.invoke('pick-subs'),
  expandVideo: (paths) => ipcRenderer.invoke('expand-video', paths),
  videoProbe: (file) => ipcRenderer.invoke('video-probe', file),
  videoCrop: (file, info) => ipcRenderer.invoke('video-crop', file, info),
  videoFrame: (file, info, s, at) => ipcRenderer.invoke('video-frame', file, info, s, at),
  videoEncode: (jobs, s, output) => ipcRenderer.invoke('video-encode', jobs, s, output),
  videoCancel: () => ipcRenderer.invoke('video-cancel'),
  onVideoProgress: (cb) => ipcRenderer.on('video-progress', (_e, file, p) => cb(file, p)),
  onVideoDone: (cb) => ipcRenderer.on('video-done', (_e, file, r) => cb(file, r)),
  pdfAssemble: (pages, opts) => ipcRenderer.invoke('pdf-assemble', pages, opts),
  pdfSplit: (files, opts) => ipcRenderer.invoke('pdf-split', files, opts),
  pdfCompress: (files, opts) => ipcRenderer.invoke('pdf-compress', files, opts),
  pdfFromImages: (files, opts) => ipcRenderer.invoke('pdf-from-images', files, opts),
  pdfSavePage: (file, index, png, opts) => ipcRenderer.invoke('pdf-save-page', file, index, png, opts),
  onPdfProgress: (cb) => ipcRenderer.on('pdf-progress', (_e, file, result) => cb(file, result)),
  estimate: (file, opts) => ipcRenderer.invoke('estimate', file, opts),
  editBase: (file, edit) => ipcRenderer.invoke('edit-base', file, edit),
  autoLevel: (file, edit) => ipcRenderer.invoke('auto-level', file, edit),
  edit: (files, opts) => ipcRenderer.invoke('edit', files, opts),
  denoise: (files, opts) => ipcRenderer.invoke('denoise', files, opts),
  denoisePreview: (file, opts, area) => ipcRenderer.invoke('denoise-preview', file, opts, area),
  setTheme: (theme) => ipcRenderer.invoke('set-theme', theme),
  onProgress: (cb) => ipcRenderer.on('progress', (_e, path, result) => cb(path, result)),
});
